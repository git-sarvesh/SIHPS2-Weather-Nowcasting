function dataSources(overrides: Partial<DataSourcesHealth> = {}): DataSourcesHealth {
  return {
    any_real_available: false,
    sources: [
      {
        source: 'MOSDAC INSAT-3D/3DR',
        availability: 'needs_credentials',
        available: false,
        is_synthetic: false,
        reason: 'MOSDAC downloads require an approved account',
        manual_instructions: 'Register at https://mosdac.gov.in/signup/',
      },
    ],
    split_feasibility: {
      requested: { train: [2015, 2022], val: [2023, 2023], test: [2024, 2025] },
      available: { 'hourly-pressure': [1979, 2020] },
      feasible: false,
      unsatisfiable: ['train'],
      proposed: { train: [2008, 2014], val: [2015, 2017], test: [2018, 2020] },
      notes: ['The required 2024-2025 test window is covered ONLY by MERA'],
    },
    ...overrides,
  }
}

describe('DataSourcePanel', () => {
  it('states plainly that no real feed is connected', () => {
    render(<DataSourcePanel dataSources={dataSources()} disclaimer={EXPERIMENTAL_DISCLAIMER} />)
    expect(screen.getByText(/synthetic demonstration data/i)).toBeTruthy()
  })

  it('never claims a blocked source is connected', () => {
    render(<DataSourcePanel dataSources={dataSources()} disclaimer={EXPERIMENTAL_DISCLAIMER} />)
    expect(screen.getByText('NEEDS ACCOUNT')).toBeTruthy()
    expect(screen.queryByText('CONNECTED')).toBeNull()
  })

  it('surfaces the historical coverage shortfall', () => {
    render(<DataSourcePanel dataSources={dataSources()} disclaimer={EXPERIMENTAL_DISCLAIMER} />)
    expect(screen.getByText(/cannot be built from currently accessible data/i)).toBeTruthy()
    expect(screen.getByText(/covered ONLY by MERA/)).toBeTruthy()
  })

  it('always renders the experimental disclaimer', () => {
    render(<DataSourcePanel dataSources={dataSources()} disclaimer={EXPERIMENTAL_DISCLAIMER} />)
    expect(screen.getByText(/NOT an official India Meteorological Department/i)).toBeTruthy()
  })

  it('renders nothing when the backend reports no data_sources block', () => {
    const { container } = render(
      <DataSourcePanel dataSources={null} disclaimer={EXPERIMENTAL_DISCLAIMER} />,
    )
    expect(container.innerHTML).toBe('')
  })

  it('shows CONNECTED only when the backend says available', () => {
    render(
      <DataSourcePanel
        dataSources={dataSources({
          any_real_available: true,
          sources: [
            {
              source: 'IMDAA/MERA (NCMRWF RDS)',
              availability: 'available',
              available: true,
              is_synthetic: false,
              reason: '12 local file(s) present',
            },
          ],
        })}
        disclaimer={EXPERIMENTAL_DISCLAIMER}
      />,
    )
    expect(screen.getByText('CONNECTED')).toBeTruthy()
  })
})

describe('EXPERIMENTAL_DISCLAIMER', () => {
  it('matches the backend wording exactly', () => {
    // Mirrors app/ingestion/base.py; drift here is a compliance bug.
    expect(EXPERIMENTAL_DISCLAIMER).toBe(
      'Experimental AI prediction for research and preparedness support only. ' +
        'This is NOT an official India Meteorological Department (IMD) warning. ' +
        'Always refer to IMD for authoritative alerts.',
    )
  })
})


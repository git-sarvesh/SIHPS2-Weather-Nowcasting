def materialise_event(
    out_dir: str | Path,
    grid: GridSpec,
    spec: EventSpec,
    *,
    terrain: Any | None = None,
    config: SyntheticConfig | None = None,
) -> dict[str, Any]:
    """Write one event sequence (``.npz``) to disk and return its manifest entry."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    if terrain is None:
        terrain, _ = build_demo_terrain(grid, cache_path=out_dir / "terrain_stack.npz")
    from app.ingestion.terrain import TerrainProcessor

    exposure = TerrainProcessor(grid, demo_mode=True).exposure_score(terrain)
    atmosphere = SyntheticAtmosphere(grid, terrain, spec, config)
    cube, diagnostics = atmosphere.build(exposure=exposure)
    path = cube.save_npz(out_dir / "sequences" / f"{spec.event_id}.npz")
    return {
        **spec.to_dict(),
        "path": str(path),
        "n_frames": cube.n_frames,
        "times": [t.isoformat() for t in cube.times],
        "label_positive_fraction": {
            key: float(np.mean(value)) for key, value in cube.labels.items() if value.dtype != np.int8
        },
        "diagnostics_summary": {
            "max_cape_j_kg": float(diagnostics["cape"].max()),
            "max_iwv_mm": float(diagnostics["iwv"].max()),
            "max_rain_rate_mmh": float(cube.labels["rain_rate_mmh"].max()),
        },
    }


def generate_demo_dataset(
    out_dir: str | Path,
    grid: GridSpec,
    *,
    specs: Sequence[EventSpec] | None = None,
    config: SyntheticConfig | None = None,
    seed: int = 7,
) -> dict[str, Any]:
    """Generate the complete demo dataset: terrain, sequences, catalogue, stations."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    event_specs = list(specs or default_event_catalog())
    terrain, exposure = build_demo_terrain(grid, seed=seed, cache_path=out_dir / "terrain_stack.npz")
    save_terrain_stack(terrain, out_dir / "terrain_stack.npz")
    np.save(out_dir / "exposure.npy", exposure.astype(np.float32))

    manifest = [materialise_event(out_dir, grid, spec, terrain=terrain, config=config) for spec in event_specs]
    catalogue = {
        "generated_at": utcnow().isoformat(),
        "disclaimer": SYNTHETIC_ATTRIBUTION,
        "grid": grid.to_dict(),
        "n_events": len(manifest),
        "events": manifest,
        "terrain": terrain.to_dict(),
    }
    (out_dir / "catalogue.json").write_text(json.dumps(catalogue, indent=2), encoding="utf-8")

    stations = ObservationCube.load_npz(manifest[0]["path"]).metadata.get("imd_stations", []) if manifest else []
    (out_dir / "imd_stations.json").write_text(
        json.dumps({"stations": stations, "disclaimer": SYNTHETIC_ATTRIBUTION}, indent=2), encoding="utf-8"
    )
    logger.info("demo dataset generated", extra={"out_dir": str(out_dir), "n_events": len(manifest)})
    return catalogue


def load_demo_cube(out_dir: str | Path, event_id: str) -> ObservationCube:
    """Load a generated demo sequence by event id."""
    return ObservationCube.load_npz(Path(out_dir) / "sequences" / f"{event_id}.npz")


def list_demo_events(out_dir: str | Path) -> list[dict[str, Any]]:
    """Read the demo catalogue event list (``[]`` when not yet generated)."""
    path = Path(out_dir) / "catalogue.json"
    if not path.exists():
        return []
    return json.loads(path.read_text(encoding="utf-8")).get("events", [])

def _iwv(levels: np.ndarray, q: np.ndarray) -> float:
    from app.ingestion.realtime.imdaa_netcdf import derive_iwv

    return float(np.asarray(derive_iwv(levels, q)).squeeze())


class TestIwvValidation:
    def test_analytic_uniform_column(self) -> None:
        levels = np.array([1000.0, 925.0, 850.0, 700.0, 500.0])
        value = _iwv(levels, np.full(5, 0.010))
        expected = 0.010 * 500.0 * 100.0 / GRAVITY
        assert value == pytest.approx(expected, rel=1e-9)

    def test_pressure_order_does_not_matter(self) -> None:
        levels = np.array([1000.0, 925.0, 850.0, 700.0, 500.0])
        q = np.array([0.014, 0.011, 0.008, 0.004, 0.002])
        forward = _iwv(levels, q)
        backward = _iwv(levels[::-1], q[::-1])
        assert forward == pytest.approx(backward, rel=1e-12)

    def test_humidity_unit_scaling_is_exactly_1000x(self) -> None:
        levels = np.array([1000.0, 925.0, 850.0, 700.0, 500.0])
        kg_per_kg = _iwv(levels, np.full(5, 0.010))
        grams_per_kg = _iwv(levels, np.full(5, 10.0))
        assert grams_per_kg == pytest.approx(kg_per_kg * 1000.0, rel=1e-9)

    def test_missing_level_yields_nan_not_a_partial_total(self) -> None:
        levels = np.array([1000.0, 925.0, 850.0, 700.0, 500.0])
        assert np.isnan(_iwv(levels, np.array([0.010, np.nan, 0.010, 0.010, 0.010])))
        # And it must not equal the complete-column value.
        complete = _iwv(levels, np.full(5, 0.010))
        assert not np.isnan(complete)

    def test_dry_column_is_exactly_zero(self) -> None:
        levels = np.array([1000.0, 925.0, 850.0, 700.0, 500.0])
        assert _iwv(levels, np.zeros(5)) == pytest.approx(0.0, abs=1e-12)

    def test_physically_realisable_column_respects_its_saturation_bound(self) -> None:
        """A realisable atmosphere cannot exceed the saturation-limited IWV.

        The bound is derived, not guessed: integrate a fully saturated profile
        over the same pressure range, then check a column that is realistic for
        a tropical monsoon atmosphere stays beneath it.
        """
        levels = np.array([1000.0, 925.0, 850.0, 700.0, 500.0])
        # q_sat at 1000/925/850/700/500 hPa for a warm, wet tropical profile.
        dewpoint = np.array([301.0, 297.0, 291.0, 279.0, 262.0])
        value = _iwv(levels, V.dewpoint_to_specific_humidity(levels, dewpoint))
        saturated = V.dewpoint_to_specific_humidity(levels, dewpoint)
        maximum = _iwv(levels, saturated)
        assert 0.0 < value <= maximum
        assert 0.0 < maximum < 100.0  # published range for extreme tropical air

    def test_supersaturated_input_is_detectable_not_silently_accepted(self) -> None:
        """q above saturation must be visible as exceeding the physical bound."""
        levels = np.array([1000.0, 925.0, 850.0, 700.0, 500.0])
        impossible = np.array([0.030, 0.025, 0.020, 0.012, 0.006])
        temperatures = np.array([293.0, 288.0, 281.0, 268.0, 253.0])
        saturation_limit = V.dewpoint_to_specific_humidity(levels, temperatures)
        # The routine integrates faithfully; the caller is responsible for
        # rejecting the input, and this documents that it is detectable.
        assert np.all(impossible > saturation_limit)
        assert _iwv(levels, impossible) > _iwv(levels, saturation_limit)

    def test_agrees_with_metpy_when_available(self) -> None:
        if not V.metpy_available():
            pytest.skip("MetPy is not installed; no independent reference available")
        levels = np.array([1000.0, 925.0, 850.0, 700.0, 500.0])
        dewpoint = np.array([288.0, 281.0, 273.0, 262.0, 250.0])
        ours = _iwv(levels, V.dewpoint_to_specific_humidity(levels, dewpoint))
        theirs = V.reference_iwv_mm(levels, dewpoint)
        assert theirs is not None
        assert abs(ours - theirs) / theirs <= V.IWV_REL_TOLERANCE

    def test_report_passes(self) -> None:
        report = V.run_iwv_validation()
        assert report.n_fail == 0, [c.detail for c in report.checks if c.status == V.FAIL]
        assert report.validated is True
        assert report.status == V.PASS
        assert report.max_relative_error is not None



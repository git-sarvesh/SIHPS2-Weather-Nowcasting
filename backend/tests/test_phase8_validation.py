class TestCapeFailurePaths:
    def test_stable_profile_with_injected_instability_fails(self) -> None:
        """A deliberately unstable profile must NOT pass the zero-CAPE check."""
        bad = V.ReferenceSounding(
            name="deliberately_unstable_but_marked_stable",
            description="Intentional mismatch: unstable values, stable expectation.",
            source="constructed for this negative test",
            pressure_hpa=(1000.0, 925.0, 850.0, 700.0, 500.0, 400.0, 300.0),
            temperature_k=(303.0, 297.0, 290.0, 280.0, 262.0, 240.0, 225.0),
            dewpoint_k=(300.0, 293.0, 284.0, 271.0, 250.0, 228.0, 210.0),
            expect_stable=True,
            expected_cape=0.0,
        )
        check = V.check_cape(bad)
        assert check.status == V.FAIL
        assert check.computed > 1000.0

    def test_missing_metpy_yields_no_reference_not_pass(self, monkeypatch) -> None:
        monkeypatch.setattr(V, "_metpy", lambda: (None, None))
        assert V.reference_cape_j_per_kg(
            (1000, 850, 700), (300, 285, 270), (290, 275, 260)
        ) is None
        profile = next(p for p in V.REFERENCE_PROFILES if not p.expect_stable)
        check = V.check_cape(profile)
        assert check.status == V.NO_REFERENCE
        assert check.reference is None
        assert "not importable" in check.reference_source

    def test_stable_profiles_still_validate_without_metpy(self, monkeypatch) -> None:
        """Analytic identities do not depend on the oracle being installed."""
        monkeypatch.setattr(V, "_metpy", lambda: (None, None))
        for profile in V.REFERENCE_PROFILES:
            if profile.expect_stable:
                assert V.check_cape(profile).status == V.PASS

    def test_run_cape_validation_honours_a_replaced_profile_set(
        self, monkeypatch
    ) -> None:
        """``run_cape_validation`` must read the module global, not a stale copy.

        Without this, every check would still run against the real profiles and a
        run with no oracle installed would be reported as validated.
        """
        monkeypatch.setattr(V, "_metpy", lambda: (None, None))
        monkeypatch.setattr(
            V, "REFERENCE_PROFILES",
            tuple(p for p in V.REFERENCE_PROFILES if not p.expect_stable),
        )
        report = V.run_cape_validation()
        assert len(report.checks) == len(V.REFERENCE_PROFILES)
        assert report.n_no_reference == len(report.checks)
        assert report.n_pass == 0
        assert report.n_fail == 0
        assert report.validated is False
        assert report.status == V.NO_REFERENCE
        assert report.reference_implementation is None

    def test_empty_report_is_not_validated(self) -> None:
        report = V.ValidationReport("cape", (), None)
        assert report.validated is False
        assert report.status == V.NO_REFERENCE
        assert report.max_relative_error is None

    def test_failing_check_forces_report_failure(self) -> None:
        check = V.CapeCheck("x", computed=999.0, reference=0.0,
                            reference_source="synthetic", status=V.FAIL)
        report = V.ValidationReport("cape", (check,), None)
        assert report.status == V.FAIL
        assert report.validated is False

    def test_input_validation_rejects_malformed_profiles(self) -> None:
        with pytest.raises(ValueError):
            parcel_ascent([1000.0, 900.0], [300.0, 290.0], [0.01, 0.01])
        with pytest.raises(ValueError):
            parcel_ascent([1000.0, 900.0, 800.0], [300.0, 290.0], [0.01, 0.01, 0.005])




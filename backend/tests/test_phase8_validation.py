def _real_cube(
    *,
    times: int = 6,
    minutes: int = 30,
    channels: int = 12,
    labels: Sequence[str] = ("thunderstorm", "rain_class", "cloudburst", "flood", "flood_soft"),
    synthetic: bool = False,
    spatial: str | None = "78-79E 29-30N",
    channel_units: bool = True,
    provenance: bool = True,
    source_file: object | None = None,
    source_sha256: str | None = None,
    extra_source_files: Sequence[object] = (),
) -> ObservationCube:
    """A minimal cube whose provenance states exactly what it is.

    Built here rather than downloaded so the gate can be exercised against known,
    *declared* provenance. ``synthetic=False`` is an explicit test fixture claim,
    never a statement that these are real observations. The default ``spatial``
    declaration matches the cube's own raster extent, so a fully eligible fixture
    has no coverage shortfall.
    """
    from app.grid import GridSpec
    from app.ingestion.base import ObservationCube, Provenance, source_file_from_disk

    grid = GridSpec.from_bbox([78.0, 29.0, 79.0, 30.0], res_km=20.0)
    stamps = [BASE + dt.timedelta(minutes=minutes * i) for i in range(times)]
    # Absent channels are NaN, not 0.0: the project's missing-data contract says a
    # missing channel must never be filled with a value, and the gate measures
    # presence with ``isfinite``.
    data = np.full((times, 12, *grid.shape), np.nan, dtype=np.float32)
    data[:, :channels] = 1.0
    cube_labels = {name: np.zeros((times, *grid.shape), dtype=np.float32) for name in labels}
    metadata: dict[str, object] = {"spatial_coverage": spatial} if spatial else {}
    if channel_units:
        from app.physics import CHANNELS

        metadata["channel_units"] = {spec.name: spec.unit for spec in CHANNELS}
    records = (
        [
            Provenance(
                source="FIXTURE" if not synthetic else "SYNTHETIC",
                product="phase-8 gate fixture",
                valid_from=stamps[0],
                valid_to=stamps[-1],
                is_synthetic=synthetic,
                attribution="test fixture" if not synthetic else "synthetic test fixture",
                source_sha256=source_sha256,
                source_path=str(source_file) if source_file else None,
                source_bytes_available=source_sha256 is not None,
                provider="Test provider",
                acquired_at=stamps[0],
                channel_units=dict(metadata.get("channel_units", {})),
                coverage=spatial,
                source_files=[source_file_from_disk(f) for f in extra_source_files],
            )
        ]
        if provenance
        else []
    )
    return ObservationCube(
        grid=grid,
        times=stamps,
        channels=data,
        provenance=records,
        labels=cube_labels,
        metadata=metadata,
    )


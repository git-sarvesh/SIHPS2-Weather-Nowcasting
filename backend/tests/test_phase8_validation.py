class TestTemporalFeasibility:
    def test_six_consecutive_30_minute_frames_are_feasible(self) -> None:
        report = assess_temporal_feasibility(
            _times_30min(6), source="INSAT-like", data_class="observation"
        )
        assert report.feasible is True
        assert report.native_cadence_minutes == 30.0
        assert report.max_contiguous_run == 6
        assert report.cadence_matches is True
        assert report.provides_required_frames is True

    def test_five_frames_are_one_short(self) -> None:
        report = assess_temporal_feasibility(
            _times_30min(5), source="short", data_class="observation"
        )
        assert report.feasible is False
        assert report.provides_required_frames is False
        assert any("short of the 6" in n for n in report.notes)

    def test_three_hourly_reanalysis_is_infeasible(self) -> None:
        """The core prohibition: IMDAA cannot be upsampled into 30-minute frames."""
        report = assess_temporal_feasibility(
            _times_cadence(8, 180), source="IMDAA", data_class="reanalysis"
        )
        assert report.feasible is False
        assert report.native_cadence_minutes == 180.0
        assert report.max_contiguous_run == 1
        assert report.cadence_matches is False
        joined = " ".join(report.notes)
        assert "NOT upsampled" in joined
        assert "repeating" in joined and "interpolating" in joined

    def test_three_hourly_data_never_reports_feasible_even_when_long(self) -> None:
        report = assess_temporal_feasibility(
            _times_cadence(500, 180), source="IMDAA-long", data_class="reanalysis"
        )
        assert report.distinct_times == 500
        assert report.feasible is False

    def test_gap_breaks_contiguity(self) -> None:
        # 0, 30, 60 then a 60-minute hole, then 120, 150, 180: runs of 3 and 3.
        first = _times_30min(3)
        second = [
            (BASE + dt.timedelta(minutes=m)).isoformat() for m in (120, 150, 180)
        ]
        report = assess_temporal_feasibility(
            first + second, source="gappy", data_class="observation"
        )
        assert report.max_contiguous_run == 3
        assert report.feasible is False
        assert report.largest_gap_minutes == 60.0
        assert any("discontinuous" in n for n in report.notes)

    def test_near_miss_cadence_is_not_accepted(self) -> None:
        """28- or 32-minute cadence is not the contract's 30 minutes."""
        report = assess_temporal_feasibility(
            _times_cadence(8, 28), source="drifting", data_class="observation"
        )
        assert report.cadence_matches is False
        assert report.feasible is False

    def test_empty_series_is_reported_not_fabricated(self) -> None:
        report = assess_temporal_feasibility([], source="empty", data_class="observation")
        assert report.feasible is False
        assert report.distinct_times == 0
        assert report.max_contiguous_run == 0
        assert report.native_cadence_minutes is None
        assert any("snapshot" in n for n in report.notes)

    def test_duplicate_and_unsorted_times_do_not_change_the_verdict(self) -> None:
        ordered = _times_30min(6)
        shuffled = list(reversed(ordered)) + ordered[:2]
        a = assess_temporal_feasibility(ordered, source="s", data_class="observation")
        b = assess_temporal_feasibility(shuffled, source="s", data_class="observation")
        assert a.feasible == b.feasible is True
        assert a.distinct_times == b.distinct_times == 6

    def test_declared_data_classes_are_all_accepted(self) -> None:
        for data_class in DATA_CLASSES:
            report = assess_temporal_feasibility(
                _times_30min(6), source="s", data_class=data_class
            )
            assert report.data_class == data_class
            # Only a true observation can be feasible; every other class is
            # measured but can never satisfy an observational requirement.
            if data_class == "observation":
                assert report.feasible is True
                assert not any(
                    "not an instrument observation" in n
                    or "generated, not observed" in n
                    for n in report.notes
                )
            else:
                assert report.feasible is False
                assert any(
                    "not an instrument observation" in n
                    or "generated, not observed" in n
                    for n in report.notes
                ), data_class

    def test_synthetic_data_is_never_temporally_feasible(self) -> None:
        """Generated fields cannot satisfy an observational cadence contract."""
        report = assess_temporal_feasibility(
            _times_30min(6), source="generated", data_class="synthetic"
        )
        assert report.cadence_matches is True       # the cadence is right
        assert report.provides_required_frames is True  # and the run is long enough
        assert report.feasible is False             # but it is not observation
        assert any("generated, not observed" in n for n in report.notes)

    def test_unknown_data_class_is_rejected(self) -> None:
        with pytest.raises(ValueError, match="unknown data_class"):
            assess_temporal_feasibility(_times_30min(6), source="s", data_class="guess")

    def test_channels_and_spatial_coverage_are_carried(self) -> None:
        report = assess_temporal_feasibility(
            _times_30min(6), source="s", data_class="observation",
            channels_available=["tir1_bt"], channels_missing=["cape"],
            spatial_coverage="77.5-80.5E 29.0-31.5N",
        )
        assert report.channels_available == ["tir1_bt"]
        assert report.channels_missing == ["cape"]
        assert report.spatial_coverage == "77.5-80.5E 29.0-31.5N"
        assert report.to_dict()["spatial_coverage"] == "77.5-80.5E 29.0-31.5N"

    def test_api_offers_no_upsampling_parameter(self) -> None:
        """Guard the central prohibition at the signature level."""
        import inspect

        parameters = inspect.signature(assess_temporal_feasibility).parameters
        for forbidden in ("upsample", "resample", "interpolate", "repeat", "step"):
            assert forbidden not in parameters, f"{forbidden!r} must not be exposed"

    def test_longest_contiguous_run_helper(self) -> None:
        base_times = [BASE + dt.timedelta(minutes=30 * i) for i in range(4)]
        assert longest_contiguous_run(base_times) == 4
        assert longest_contiguous_run([]) == 0
        assert longest_contiguous_run([BASE]) == 1
        broken = [BASE, BASE + dt.timedelta(minutes=30), BASE + dt.timedelta(minutes=90)]
        assert longest_contiguous_run(broken) == 2

    def test_cadence_matcher_is_exact(self) -> None:
        assert cadence_matches_contract(30.0, 30) is True
        assert cadence_matches_contract(28.0, 30) is False
        assert cadence_matches_contract(180.0, 30) is False
        assert cadence_matches_contract(None, 30) is False

    def test_report_serialises_every_check(self) -> None:
        payload = V.run_iwv_validation().to_dict()
        assert payload["feature"] == "iwv"
        assert len(payload["checks"]) >= 6
        names = {c["name"] for c in payload["checks"]}
        assert "missing_level_yields_nan" in names
        assert "humidity_unit_scaling" in names
        assert "pressure_order_invariance" in names
        assert "dry_column_is_zero" in names

    def test_missing_metpy_downgrades_only_the_oracle_check(self, monkeypatch) -> None:
        monkeypatch.setattr(V, "_metpy", lambda: (None, None))
        assert V.reference_iwv_mm([1000, 850, 700], [288, 275, 260]) is None
        report = V.run_iwv_validation()
        # The analytic properties are oracle-free, so the feature still validates.
        assert report.validated is True
        assert report.n_fail == 0
        assert report.n_no_reference == 1
        assert report.reference_implementation is None

    def test_dewpoint_round_trip_is_exact(self) -> None:
        p = np.array([1000.0, 925.0, 850.0, 700.0, 500.0, 300.0])
        dewpoint = np.array([295.0, 288.0, 281.0, 268.0, 253.0, 230.0])
        q = V.dewpoint_to_specific_humidity(p, dewpoint)
        assert np.allclose(V.sounding_to_dewpoint_k(p, q), dewpoint, atol=1e-8)
        assert np.all(q > 0)
        assert np.all(q < 0.05)




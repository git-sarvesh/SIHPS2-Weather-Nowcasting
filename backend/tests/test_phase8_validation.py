# CAPE: stable / unstable behaviour against an independent oracle
# --------------------------------------------------------------------------- #
def _cape_of(profile: V.ReferenceSounding) -> float:
    return float(
        parcel_ascent(
            np.asarray(profile.pressure_hpa),
            np.asarray(profile.temperature_k),
            profile.specific_humidity_kgkg,
        )["cape"]
    )


class TestCapeAgainstIndependentReference:
    def test_stable_profiles_have_exactly_zero_cape(self) -> None:
        """The regression this phase exists to prevent.

        A saturated parcel must cool as it rises. A reversed sign in that
        integration made stable profiles report ~2810 J kg-1.
        """
        stable = [p for p in V.REFERENCE_PROFILES if p.expect_stable]
        assert len(stable) >= 3
        for profile in stable:
            assert _cape_of(profile) <= 5.0, f"{profile.name} reported {_cape_of(profile)}"

    def test_rising_parcel_always_cools(self) -> None:
        """A parcel lifted through the atmosphere must never warm."""
        for profile in V.REFERENCE_PROFILES:
            parcel = parcel_ascent(
                np.asarray(profile.pressure_hpa),
                np.asarray(profile.temperature_k),
                profile.specific_humidity_kgkg,
            )["parcel_temperature_k"]
            assert np.all(np.diff(parcel) <= 1e-9), (
                f"{profile.name}: parcel warmed with height: {parcel}"
            )

    def test_unstable_profiles_have_large_positive_cape(self) -> None:
        unstable = [p for p in V.REFERENCE_PROFILES if not p.expect_stable]
        assert len(unstable) >= 2
        for profile in unstable:
            cape = _cape_of(profile)
            assert cape > 1000.0, f"{profile.name} reported only {cape} J kg-1"

    def test_stable_cape_is_always_below_unstable_cape(self) -> None:
        stable = min(_cape_of(p) for p in V.REFERENCE_PROFILES if p.expect_stable)
        unstable = max(_cape_of(p) for p in V.REFERENCE_PROFILES if not p.expect_stable)
        assert stable < unstable

    def test_agrees_with_metpy_when_available(self) -> None:
        if not V.metpy_available():
            pytest.skip("MetPy is not installed; no independent reference available")
        for profile in V.REFERENCE_PROFILES:
            check = V.check_cape(profile)
            if profile.expect_stable:
                assert check.status == V.PASS, f"{profile.name}: {check.detail}"
                assert check.reference == 0.0
            else:
                assert check.reference is not None
                assert check.status == V.PASS, f"{profile.name}: {check.detail}"
                relative = abs(check.computed - check.reference) / check.reference
                assert relative <= V.CAPE_REL_TOLERANCE

    def test_report_passes_and_reports_realised_error(self) -> None:
        report = V.run_cape_validation()
        assert report.n_fail == 0, [c.detail for c in report.checks if c.status == V.FAIL]
        assert report.validated is True
        assert report.status == V.PASS
        # Screening-grade accuracy must be visible, not hidden behind pass/fail.
        assert report.max_relative_error is not None
        assert report.max_relative_error <= V.CAPE_REL_TOLERANCE

    def test_report_serialises(self) -> None:
        payload = V.run_cape_validation().to_dict()
        assert payload["feature"] == "cape"
        assert len(payload["checks"]) == len(V.REFERENCE_PROFILES)
        for check in payload["checks"]:
            assert {"name", "computed", "reference", "status", "reference_source"} <= set(check)


